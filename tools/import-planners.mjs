#!/usr/bin/env node
// Imports Tabula Campus planner HTML files into the mobile app.
//
//   node tools/import-planners.mjs <folder-with-planner-html> [more folders...]
//
// For every *-Planner_<edition>.html it finds, it writes:
//   mobile/src/planners/data/<id>.json   the planner's data (book, programmes, rules, sheets...)
//   mobile/assets/trackers/<name>.xlsx   the Excel tracker the HTML file carries inside it
// and regenerates mobile/src/planners/catalog.ts and mobile/src/planners/art.json.
// Run it again when a new edition of the planners is built.

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const mobile = join(root, 'mobile');
const dataDir = join(mobile, 'src/planners/data');
const trackerDir = join(mobile, 'assets/trackers');

const inputs = process.argv.slice(2);
if (!inputs.length) {
  console.error('usage: node tools/import-planners.mjs <folder> [folder...]');
  process.exit(1);
}

function findHtml(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) out.push(...findHtml(p));
    else if (/-Planner_[\d-]+\.html$/.test(name)) out.push(p);
  }
  return out;
}

function extractData(html, file) {
  const open = '<script id="data" type="application/json">';
  const i = html.indexOf(open);
  if (i < 0) throw new Error(`${file}: no planner data block`);
  const j = html.indexOf('</script>', i);
  return JSON.parse(html.slice(i + open.length, j));
}

const files = inputs.flatMap((d) => findHtml(resolve(d))).sort();
if (!files.length) {
  console.error('No planner HTML files found.');
  process.exit(1);
}

rmSync(dataDir, { recursive: true, force: true });
rmSync(trackerDir, { recursive: true, force: true });
mkdirSync(dataDir, { recursive: true });
mkdirSync(trackerDir, { recursive: true });

const catalog = [];
let sharedArt = null;

for (const file of files) {
  const D = extractData(readFileSync(file, 'utf8'), basename(file));
  const id = D.product.id;

  // The Excel tracker becomes a real file; the app shares it from its assets.
  const trackers = [];
  for (const e of D.embeds || []) {
    writeFileSync(join(trackerDir, e.name), Buffer.from(e.b64, 'base64'));
    trackers.push(e.name);
  }

  // Art shared by every planner (mark, sticker, underline, tab icons) is stored once.
  // react-native-svg does not decode character references inside <text>, so decode them here.
  const decode = (svg) => svg.replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCodePoint(parseInt(h, 16))).replace(/&#(\d+);/g, (_, d) => String.fromCodePoint(+d));
  const motif = decode(D.art.motif);
  const { motif: _m, ...shared } = D.art;
  sharedArt ??= shared;

  const out = {
    ...D,
    embeds: undefined,
    art: { motif },
    // Designer notes never show in the app.
    book: D.book.filter((b) => b.type !== 'design'),
    trackers,
  };
  writeFileSync(join(dataDir, `${id}.json`), JSON.stringify(out));

  catalog.push({
    id,
    uni: D.uni.key,
    uniName: D.uni.name,
    uniShort: D.uni.short,
    deptShort: D.dept.short,
    deptName: D.dept.name,
    title: D.product.title,
    edition: D.product.edition,
    accent: `#${D.dept.accent}`,
    tint: `#${D.dept.accent_light}`,
    trackers,
    motif,
  });
  console.log(`${id.padEnd(28)} ${D.product.title}  (${trackers.length} tracker)`);
}

writeFileSync(join(mobile, 'src/planners/art.json'), JSON.stringify(sharedArt));

const loaders = catalog.map((c) => `  '${c.id}': () => require('./data/${c.id}.json'),`).join('\n');
const trackerAssets = catalog
  .flatMap((c) => c.trackers)
  .map((t) => `  '${t}': require('../../assets/trackers/${t}'),`)
  .join('\n');

writeFileSync(
  join(mobile, 'src/planners/catalog.ts'),
  `// Generated by tools/import-planners.mjs - do not edit by hand.
import type { PlannerData } from './types';

export type CatalogEntry = {
  id: string;
  uni: string;
  uniName: string;
  uniShort: string;
  deptShort: string;
  deptName: string;
  title: string;
  edition: string;
  accent: string;
  tint: string;
  trackers: string[];
  motif: string;
};

export const CATALOG: CatalogEntry[] = ${JSON.stringify(catalog, null, 2)};

// Each planner's data is loaded only when it is opened.
const LOADERS: Record<string, () => PlannerData> = {
${loaders}
};

export function loadPlanner(id: string): PlannerData | null {
  return LOADERS[id] ? LOADERS[id]() : null;
}

export const TRACKER_ASSETS: Record<string, number> = {
${trackerAssets}
};
`,
);

console.log(`\n${catalog.length} planners imported.`);
if (!existsSync(join(mobile, 'src/planners/types.ts'))) console.warn('Note: mobile/src/planners/types.ts is missing.');
